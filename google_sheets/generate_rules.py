"""Generate Apps Script rules without importing Flask or fetching vocabularies."""

import ast
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate():
    tree = ast.parse((ROOT / "metadatalib/spec.py").read_text())
    groups = {}
    supported = {
        "columns_named",
        "columns_matching",
        "values_matching",
        "unique_values_for",
        "some_value_for",
        "values_in_set",
    }
    for node in tree.body:
        if not isinstance(node, ast.Assign) or not isinstance(node.value, ast.List):
            continue
        name = node.targets[0].id
        if not name.startswith("specs_"):
            continue
        rules = []
        for call in node.value.elts:
            kind = call.func.id
            if kind not in supported:
                raise ValueError(f"Unsupported rule: {kind}")
            args = [
                (
                    {"vocabulary": arg.id}
                    if isinstance(arg, ast.Name)
                    else ast.literal_eval(arg)
                )
                for arg in call.args
            ]
            rules.append({"kind": kind, "args": args})
        groups[name] = rules
    # Keep laboratory output columns tied to the supplied R template.
    template = (ROOT / "plate_review.R").read_text()
    aliases = {
        "SampleType": "sample_type",
        "date_collected": "year_collected",
        "udi_coord": "barcode_coord",
        "column peaks_present": "column_peaks_present",
    }
    columns = {}
    for run, variable in [("Amplicon", "amplicon_cols"), ("Shotgun", "shotgun_cols")]:
        match = re.search(rf"{variable}\s*<-\s*c\((.*?)\)\s*\n", template, re.S)
        if not match:
            raise ValueError(f"Missing R column list: {variable}")
        names = re.findall(r"[\"']([^\"']+)[\"']", match.group(1))
        columns[run] = [aliases.get(name, name) for name in names]
    columns["WGS"] = columns["Shotgun"]
    return (
        "// Generated by generate_rules.py; do not edit.\nconst CHOP_RULES = "
        + json.dumps(groups, indent=2)
        + ";\nconst CHOP_PLATE_COLUMNS = "
        + json.dumps(columns, indent=2)
        + ";\n"
    )


if __name__ == "__main__":
    (ROOT / "google_sheets/Rules.gs").write_text(generate())
